const DICTS: Record<Lang, Dict> = { en, ar, fr, es };
export type Key = keyof typeof en;

interface I18n {
  lang: Lang;
  dir: "ltr" | "rtl";
  setLang: (l: Lang) => void;
  t: (k: Key, vars?: Record<string, string | number>) => string;
  reason: (r: ReasonCode) => string;
  verdict: (v: Verdict) => string;
  status: (s: CaseStatus) => string;
  money: (n: number, currency?: string) => string;
  date: (iso: string) => string;
  locale: string;
}

const LOCALES: Record<Lang, string> = { en: "en-GB", ar: "ar-SA", fr: "fr-FR", es: "es-ES" };
const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("rb-lang") as Lang | null;
    if (saved && saved in DICTS) return saved;
  } catch {
    /* storage unavailable */
  }
  const nav = navigator.language.slice(0, 2) as Lang;
  return nav in DICTS ? nav : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const dir = lang === "ar" ? "rtl" : "ltr";
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);
  const value = useMemo<I18n>(() => {
    const d = DICTS[lang];
    const locale = LOCALES[lang];
    const nf = new Map<string, Intl.NumberFormat>();
    const t = (k: Key, vars?: Record<string, string | number>) => {
      let s = d[k] ?? en[k] ?? k;
      if (vars) for (const [n, v] of Object.entries(vars)) s = s.replace(`{${n}}`, String(v));
      return s;
    };
    return {
      lang,
      dir,
      locale,
      setLang: (l) => {
        try {
          localStorage.setItem("rb-lang", l);
        } catch {
          /* storage unavailable */
        }
        setLangState(l);
      },
      t,
      reason: (r) => t(`reason.${r}` as Key),
      verdict: (v) => t(`verdict.${v}` as Key),
      status: (s) => t(`status.${s}` as Key),
      money: (n, currency = "USD") => {
        if (!nf.has(currency)) nf.set(currency, new Intl.NumberFormat(locale, { style: "currency", currency, numberingSystem: "latn" }));
        return nf.get(currency)!.format(n);
      },
      date: (iso) => new Intl.DateTimeFormat(locale, { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit", numberingSystem: "latn" }).format(new Date(iso)),
    };
  }, [lang, dir]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n outside provider");
  return v;
}
